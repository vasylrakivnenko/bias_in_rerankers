"""
Appendix table for the companion experiment on published résumé examples.

The paper says the companion run's directions and magnitudes differ from the
synthetic audit; this table shows them (reviewer item 6). It reads only the
banked summary in results/realistic_pool_four_rerankers.json and never
rescores anything.

Output: results/tex/companion_table.tex
Run:    venv/bin/python code/companion_table.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "code"))

from model_labels import model_label  # noqa: E402

SRC = ROOT / "results" / "realistic_pool_four_rerankers.json"
OUT = ROOT / "results" / "tex" / "companion_table.tex"
GROUPS = ("male", "female", "neutral", "unknown")


def main():
    data = json.loads(SRC.read_text())
    lines = ["% Generated by code/companion_table.py -- do not edit by hand.",
             r"\begin{tabular}{lrrrrrrr}", r"\toprule",
             r"Reranker & Comparisons & All & Male-typed & Female-typed & Neutral & "
             r"Unlabeled & Top-3 flips \% \\",
             r"\midrule"]
    first = None
    for m in data["models"].values():
        s = m["summary"]
        n = {g: s["by_stereotype"][g]["n"] for g in GROUPS}
        first = first or n
        assert n == first, "every model must be scored on the same comparisons"
        cells = [f"{s['overall']['score_gap']['tie_aware_pct_male']:.1f}"]
        cells += [f"{s['by_stereotype'][g]['score_gap']['tie_aware_pct_male']:.1f}" for g in GROUPS]
        lines.append(f"{model_label(m['model'])} & {s['overall']['n']:,} & "
                     + " & ".join(cells)
                     + f" & {s['overall']['top3']['flip_rate_pct']:.1f} \\\\")
    lines += [r"\midrule",
              r"Comparisons per group & & & " + " & ".join(f"{first[g]:,}" for g in GROUPS)
              + r" & \\",
              r"\bottomrule", r"\end{tabular}"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Saved -> {OUT}")


if __name__ == "__main__":
    main()
