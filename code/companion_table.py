"""
Appendix tables for the companion experiment on published résumé examples.

The paper says the companion run's directions and magnitudes differ from the
synthetic audit; companion_table.tex shows them (reviewer item 6), with each
reranker's male-typed minus female-typed difference (reviewer item P10).
companion_by_construction.tex splits the comparisons by how each pair was built
and sets each reranker's mean absolute score gap beside the synthetic audit's
(reviewer item P2). Both read only banked outputs -- the summary in
results/realistic_pool_four_rerankers.json and the statistics that
code/companion_statistics.py derives from it in results/companion_statistics.json
-- and never rescore anything.

Output: results/tex/companion_table.tex, results/tex/companion_by_construction.tex
Run:    venv/bin/python code/companion_table.py
        (after venv/bin/python code/companion_statistics.py, whose output it reads)
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "code"))

from model_labels import model_label  # noqa: E402

SRC = ROOT / "results" / "realistic_pool_four_rerankers.json"
STATS = ROOT / "results" / "companion_statistics.json"
OUT = ROOT / "results" / "tex" / "companion_table.tex"
OUT_CONSTRUCTION = ROOT / "results" / "tex" / "companion_by_construction.tex"
GROUPS = ("male", "female", "neutral", "unknown")
# companion_statistics.py's construction groups, in print order, with their row labels
CONSTRUCTION_ROWS = {"prepended": "Name prepended", "swap_in_window": "Swapped, in window",
                     "swap_truncated": "Swapped, truncated"}


def num(x, nd=1):
    # A true minus sign, as in the other tables; a value rounding to zero prints as 0.0.
    t = f"{x:.{nd}f}"
    if float(t) == 0:
        t = f"{0:.{nd}f}"
    return "$-$" + t[1:] if t.startswith("-") else t


def sig4(x):
    """Four significant figures in fixed notation, as in same_gender_name_swap.tex."""
    if x == 0:
        return "0"
    d = max(0, 3 - int(math.floor(math.log10(abs(x)))))
    s = f"{x:.{d}f}"
    if d and abs(float(s)) >= 10 ** (4 - d):      # rounding carried into a fifth figure
        s = f"{x:.{d - 1}f}"
    return s


def load_statistics(data):
    """companion_statistics.json, checked against the summary it was derived from."""
    stats = json.loads(STATS.read_text())
    stale = (stats["source"]["summary_script_version"] != data["script_version"]
             or list(stats["models"]) != list(data["models"])
             or "by_construction" not in stats)
    if not stale:
        for short, m in data["models"].items():
            s = m["summary"]
            banked = {"overall": s["overall"]["score_gap"]["tie_aware_pct_male"],
                      **{g: s["by_stereotype"][g]["score_gap"]["tie_aware_pct_male"]
                         for g in GROUPS}}
            shares = stats["models"][short]["tie_aware_pct_male"]["all_comparisons"]
            stale = stale or {c: round(v, 2) for c, v in shares.items()} != banked
    if stale:
        raise AssertionError(f"{STATS.name} does not match {SRC.name}: "
                             "re-run code/companion_statistics.py first")
    return stats


def companion_table(data, stats):
    # Headers on two short lines: on one line they set the column widths, and the
    # paper's \resizebox{\textwidth} would shrink the type to ~8.2 pt (~9.9 pt this way).
    lines = ["% Generated by code/companion_table.py -- do not edit by hand.",
             r"\begin{tabular}{lrrrrrrrr}", r"\toprule",
             r" & & & Male- & Female- & Evenly & & & Top-3 \\",
             r"Reranker & Comparisons & All & typed & typed & split & Unlabeled & M$-$F & "
             r"flips \% \\",
             r"\midrule"]
    first = None
    for short, m in data["models"].items():
        s = m["summary"]
        n = {"all": s["overall"]["n"], **{g: s["by_stereotype"][g]["n"] for g in GROUPS}}
        first = first or n
        assert n == first, "every model must be scored on the same comparisons"
        assert n["all"] == sum(n[g] for g in GROUPS), "the groups must partition the comparisons"
        # Unrounded shares (load_statistics checked them against the summary): the summary
        # rounds to two decimals, and rounding those again misprinted 55.848 as 55.9.
        shares = stats["models"][short]["tie_aware_pct_male"]["all_comparisons"]
        cells = [f"{shares[c]:.1f}" for c in ("overall",) + GROUPS]
        # male-typed minus female-typed, also from the unrounded shares
        cells.append(num(stats["models"][short]["male_minus_female"]["all_comparisons"]))
        top = s["overall"]["top3"]
        lines.append(f"{model_label(m['model'])} & {s['overall']['n']:,} & "
                     + " & ".join(cells)
                     + f" & {100 * top['n_flips'] / s['overall']['n']:.1f} \\\\")
    lines += [r"\midrule",
              r"Comparisons per group & & " + " & ".join(f"{first[g]:,}" for g in ("all",) + GROUPS)
              + r" & & \\",
              r"\bottomrule", r"\end{tabular}"]
    return lines


def by_construction_table(data, stats):
    lines = ["% Generated by code/companion_table.py -- do not edit by hand.",
             r"\begin{tabular}{lrrrrrr}", r"\toprule",
             r" & & Tie-aware & & \multicolumn{3}{c}{Top-3 flips} \\",
             r"\cmidrule(l){5-7}",
             r"Pair built by & Comparisons & \%\,M & Mean $|\Delta|$ & \% & Male only & "
             r"Female only \\",
             r"\midrule"]
    for i, (short, m) in enumerate(data["models"].items()):
        by = stats["models"][short]["by_construction"]
        assert sum(by[c]["n"] for c in CONSTRUCTION_ROWS) == m["summary"]["overall"]["n"], \
            "the construction groups must partition the comparisons"
        lines += ([r"\addlinespace"] if i else []) + [
            rf"\multicolumn{{7}}{{l}}{{\textit{{{model_label(m['model'])}}}}} \\"]
        for c, label in CONSTRUCTION_ROWS.items():
            g, t = by[c], by[c]["top3"]
            lines.append(rf"\quad {label} & {g['n']:,} & {g['tie_aware_pct_male']:.1f} & "
                         rf"{sig4(g['mean_abs_delta'])} & {t['flip_rate_pct']:.1f} & "
                         rf"{t['male_form_only']} & {t['female_form_only']} \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\par\medskip",
              r"\begin{tabular}{lrrr}", r"\toprule",
              r" & \multicolumn{2}{c}{Mean $|\Delta|$} & \\",
              r"\cmidrule(lr){2-3}",
              r"Reranker & Companion, in window & Synthetic audit & Synthetic / companion \\",
              r"\midrule"]
    all_ratios = []
    for short, m in data["models"].items():
        a = stats["models"][short]["mean_abs_delta"]
        lines.append(f"{model_label(m['model'])} & {sig4(a['companion_in_window'])} & "
                     f"{sig4(a['synthetic_audit'])} & "
                     f"{a['ratio_synthetic_to_companion_in_window']:.1f} \\\\")
        all_ratios.append(a["synthetic_audit"] / a["companion_all_comparisons"])
    n_syn = {v["synthetic_audit"]["n_pairs"] for v in stats["models"].values()}
    assert len(n_syn) == 1, "every model's synthetic mean must cover the same pairs"
    window = next(iter(data["models"].values()))["token_window"]["tokenizer_model_max_length"]
    bc = stats["by_construction"]
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\par\smallskip{\footnotesize\raggedright "
              f"Name prepended: a frequency-matched given name prepended; in "
              f"{bc['n_prepended_document_carried_a_name']} of the {bc['n_prepended']:,} "
              f"comparisons, both versions also keep the document's own detected name, which "
              f"could not be swapped. Swapped: an existing name or pronouns exchanged, with at "
              f"least one marker inside the {window}-token window (in window) or none (truncated: "
              f"the reranker saw two identical inputs, which tie and cannot flip); the split "
              f"depends on the tokenizer. Male only (Female only): flips in which only the "
              f"male-associated (female-associated) version made the top three. Mean "
              f"$|\\Delta|$ is on each model's own score scale, over the comparisons with a "
              f"marker in the window and over the synthetic audit's {n_syn.pop():,} pairs; "
              f"counting the truncated comparisons as zero gaps would put the ratios at "
              f"{min(all_ratios):.1f} to {max(all_ratios):.1f}.\\par}}"]
    return lines


def main():
    data = json.loads(SRC.read_text())
    stats = load_statistics(data)
    for path, lines in ((OUT, companion_table(data, stats)),
                        (OUT_CONSTRUCTION, by_construction_table(data, stats))):
        path.write_text("\n".join(lines) + "\n")
        print(f"Saved -> {path}")


if __name__ == "__main__":
    main()
